"""Builds data/ClassicItemExpansion.lua: the expansion of every gathering item
that exists in MoP Classic, for the node tooltip's "Expansion" line.

Why a table: on the Classic clients GetItemInfo's expansion ID is unusable.
Checked on wago.tools (2026-10-07): MoP Classic 5.5.4 gives 254 ("unknown")
to vanilla items such as Peacebloom and Oily Blackmouth, and 0 ("Vanilla") to
Pandaria items such as Ghost Iron Ore; TBC Anniversary 2.5.6 gives 254 to
Fel Iron Ore too. Retail's own data is right, so the table is taken from it.

Kept: Trade Goods (class 7) whose subclass a gathering node can drop - metal
and stone, herb, meat (raw fish), elemental, jewelcrafting, enchanting - with
a Retail expansion from 1 (TBC) to 4 (MoP), and present in MoP Classic's item
data. Anything absent from the table is vanilla (0) for FarmMap.

Usage:  python tools/make_classic_expansions.py [cache_dir]
The three CSVs are downloaded from wago.tools into cache_dir (default: a temp
folder) unless they are already there.
"""
import csv
import os
import sys
import tempfile
import urllib.request

csv.field_size_limit(10 ** 9)

SOURCES = {
    "item.csv":       "https://wago.tools/db2/Item/csv?branch=wow",
    "sparse.csv":     "https://wago.tools/db2/ItemSparse/csv?branch=wow",
    "sparse_mop.csv": "https://wago.tools/db2/ItemSparse/csv?branch=wow_classic",
}
SUBCLASSES = {4: "Jewelcrafting", 7: "Metal & Stone", 8: "Meat",
              9: "Herb", 10: "Elemental", 12: "Enchanting"}
EXPANSIONS = {1: "The Burning Crusade", 2: "Wrath of the Lich King",
              3: "Cataclysm", 4: "Mists of Pandaria"}
# Retail's own data is wrong for these.
OVERRIDES = {
    22788: 1,  # Flame Cap: an Outland herb, listed as vanilla on Retail
}

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "data", "ClassicItemExpansion.lua")


def fetch(cache):
    os.makedirs(cache, exist_ok=True)
    for name, url in SOURCES.items():
        path = os.path.join(cache, name)
        if not os.path.exists(path):
            print("downloading", url)
            urllib.request.urlretrieve(url, path)


def rows(cache, name):
    with open(os.path.join(cache, name), encoding="utf-8") as f:
        yield from csv.DictReader(f)


def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        tempfile.gettempdir(), "farmmap-wago")
    fetch(cache)

    item = {int(r["ID"]): (int(r["ClassID"]), int(r["SubclassID"]))
            for r in rows(cache, "item.csv")}
    retail = {int(r["ID"]): int(r["ExpansionID"])
              for r in rows(cache, "sparse.csv")}
    mop = {int(r["ID"]) for r in rows(cache, "sparse_mop.csv")}

    table = {}
    for iid in mop:
        cls_sub = item.get(iid)
        exp = OVERRIDES.get(iid, retail.get(iid))
        if cls_sub and cls_sub[0] == 7 and cls_sub[1] in SUBCLASSES \
           and exp in EXPANSIONS:
            table[iid] = exp

    lines = [
        "-- GENERATED by tools/make_classic_expansions.py - do not edit by hand,",
        "-- rerun the script. Gathering items of TBC to MoP -> expansion ID, used",
        "-- on the Classic clients, whose own item data gets expansions wrong.",
        "-- Items absent from the table are vanilla (0).",
        "",
        "local _, ns = ...",
        "",
        "local t = {}",
        "ns.classicItemExpansion = t",
        "",
        "local function Add(expansion, ids)",
        "    for _, id in ipairs(ids) do t[id] = expansion end",
        "end",
    ]
    for exp, label in EXPANSIONS.items():
        ids = sorted(i for i, e in table.items() if e == exp)
        lines += ["", "-- %d = %s (%d items)" % (exp, label, len(ids)),
                  "Add(%d, {" % exp]
        for k in range(0, len(ids), 10):
            lines.append("    " + ", ".join(str(i) for i in ids[k:k + 10]) + ",")
        lines.append("})")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d items to %s" % (len(table), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
